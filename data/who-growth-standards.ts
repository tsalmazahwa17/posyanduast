export function getWhoReference(
  metric: "weight" | "height",
  gender: GrowthGender,
  month: number
): WhoGrowthPoint {
  const clampedMonth = Math.max(0, Math.min(60, Math.round(month)));
  const source =
    metric === "weight" ? WHO_WEIGHT_FOR_AGE[gender] : WHO_HEIGHT_FOR_AGE[gender];

  return source[clampedMonth];
}
